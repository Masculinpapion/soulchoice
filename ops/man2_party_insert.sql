-- tohum başvurular: kadın test kullanıcılarından 0-3 (deterministik appcnt)
insert into public.applications (invitation_id, applicant_id, status, created_at)
select inv.id, w.id, 'pending', now() - (random() * interval '3 hours')
from m2
join public.invitations inv on inv.owner_id = m2.id and inv.status = 'active'
cross join lateral (
  select u.id from public.users u
  where u.is_test_user and u.gender = 'female'
  order by random()
  limit m2.appcnt
) w
on conflict do nothing;

